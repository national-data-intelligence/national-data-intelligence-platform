#!/usr/bin/env python3
"""Compile bundle/roles/*.yaml → 7_security/opa/policies/*.rego.

For each role YAML, emits a Rego file under nhdw.authz.<role-id>. A top-
level common.rego is preserved (not generated) and routes incoming
requests to the right per-role decision.

The output is purely declarative — the PEP at each access point posts
(user.role, action.verb, resource.subject, resource.granularity,
context.purpose_of_use) and OPA returns
    { "allow": bool, "reason": "..." }
plus optional obligations.

Run from anywhere:
    python3 7_security/opa/scripts/compile.py
"""
from __future__ import annotations

import sys
from pathlib import Path

try:
    import yaml
except ImportError:
    print("PyYAML missing — pip install pyyaml", file=sys.stderr)
    sys.exit(1)

import json


def rego_list(items):
    """Format a Python list as a Rego array literal (double-quoted strings)."""
    return json.dumps(items)

REPO = Path(__file__).resolve().parents[3]
ROLES_DIR = REPO / "bundle" / "roles"
OUT_DIR = REPO / "7_security" / "opa" / "policies"


def role_id_to_module(role_id: str) -> str:
    return "role_" + role_id.lower().replace("-", "_")


def emit_role_rego(role: dict) -> str:
    """Generate Rego for one role's permission set."""
    role_id = role["id"]
    module = role_id_to_module(role_id)
    perms = role.get("permissions") or []
    lines = [
        f"# Generated by 7_security/opa/scripts/compile.py — DO NOT EDIT BY HAND.",
        f"# Source: bundle/roles/{role_id.lower()}.yaml",
        f"package nhdw.authz.role_{role_id.lower().replace('-', '_')}",
        "",
        "import rego.v1",
        "",
        f'role_id := "{role_id}"',
        f'phase   := {role["phase_activated"]}',
        f"",
        "default allow := false",
        "",
    ]
    if not perms:
        intentional = bool(role.get("intentional_deny"))
        marker = "intentional" if intentional else "stub (not yet activated)"
        lines += [
            f"# Data-plane deny-all — {marker}.",
            "# Permissions list is empty; allow stays false. The PEP reads this",
            "# as a hard deny for any mart read.",
            "",
            "decision := {",
            '  "allow":  allow,',
            f'  "reason": "{role_id} data-plane deny-all ({marker})",',
            "}",
            "",
        ]
        return "\n".join(lines)

    # Emit one `allow` rule per permission entry; OPA's default-deny means
    # ANY match grants. The PEP requests one decision at a time so the
    # union semantics here are exactly what we want.
    for i, perm in enumerate(perms):
        subject = perm["subject"]
        members = perm["members"]
        granularity = perm["granularity"]
        verbs = perm.get("verbs") or []
        purposes = perm.get("purpose_of_use") or []
        data_classes = perm.get("data_class") or []
        sensitivity = perm.get("sensitivity") or []

        # We keep matching simple — verb in list, subject equals, granularity
        # equals, purpose in list. Scope evaluation is deferred to the PEP
        # which has the full user.attributes context.
        lines += [
            f"# permission[{i}]: {subject} / members={members} / gran={granularity} / verbs={verbs}",
            f"allow if {{",
            f'  input.resource.subject == "{subject}"',
            f"  input.action.verb in {rego_list(verbs)}",
            f"  input.resource.granularity == \"{granularity}\"",
            f"  input.context.purpose_of_use in {rego_list(purposes)}",
        ]
        if data_classes:
            lines.append(f"  input.resource.data_class in {rego_list(data_classes)}")
        if members == "self":
            lines.append('  input.resource.is_self == true')
        if sensitivity:
            lines += [
                f"  # sensitivity grant — empty means default; here listed: {sensitivity}",
                f"  input.resource.sensitivity in {rego_list(sensitivity + ['default'])}",
            ]
        else:
            lines.append('  input.resource.sensitivity in ["default", ""]')
        lines.append("}")
        lines.append("")

    lines += [
        "# Top-level decision object — what the PEP gets back.",
        "decision := {",
        '  "allow":   allow,',
        f'  "reason":  sprintf("evaluated against {role_id}: allow=%v", [allow]),',
        "}",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    if not ROLES_DIR.is_dir():
        print(f"roles dir not found: {ROLES_DIR}", file=sys.stderr)
        return 1
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    written = []
    for yaml_path in sorted(ROLES_DIR.glob("*.yaml")):
        with yaml_path.open() as f:
            doc = yaml.safe_load(f)
        role = doc["role"]
        out_path = OUT_DIR / f"{role_id_to_module(role['id'])}.rego"
        out_path.write_text(emit_role_rego(role))
        written.append((role["id"], out_path.name, len(role.get("permissions") or [])))

    print("compiled:")
    for rid, fname, n in written:
        print(f"  {rid:14}  →  policies/{fname}  ({n} permission entries)")
    print(f"total: {len(written)} role policies")
    return 0


if __name__ == "__main__":
    sys.exit(main())
