#!/usr/bin/env python3
"""sync-om-classification.py — ONE-WAY export of OpenMetadata column tags
into `ops_perm.column_classification` (+ the committed seed YAML).

Direction and authority (the settled design — never violate):
  OpenMetadata AUTHORS classification; `ops_perm` (a committed seed loaded at
  boot) is what OPA ENFORCES. OM is never in the enforcement path: this sync
  writes rows with managed_by='openmetadata' and NEVER touches rows whose
  managed_by is 'seed' or 'steward'. Governance must hold with OM down —
  this script simply not running changes nothing.

Tag mapping (conservative; extend deliberately, in review):
  PII.Sensitive     → sensitivity=restricted, mask_class=drop,     pii=true
  PII.NonSensitive  → sensitivity=default,    mask_class=none,     pii=true
  (all other tags are catalog-only and ignored here)

Guards:
  * the target table is created by the governance workstream in
    17_perm_schemas.sql — when it does not exist yet, this exits 0 with a
    note (nothing is created here; not our table to create);
  * dry-run by default; writing needs BOTH --apply and
    OM_CLASS_SYNC_ENABLED=true (feature flag, default off);
  * DB and OM are taken from env only: OM_API, OM_JWT, CLASS_DB_DSN.

Seed round-trip: rows this sync manages are also written to
  bundle/seed-pack/app/security/column_classification.openmetadata.yaml
(generated file; the loader's seed file may include/merge it). Commit it so a
cold boot reproduces the OM-authored classification without OM.
"""
from __future__ import annotations

import argparse
import json
import os
import pathlib
import ssl
import sys
import urllib.parse
import urllib.request

REPO = pathlib.Path(__file__).resolve().parents[2]
GENERATED = REPO / "bundle/seed-pack/app/security/column_classification.openmetadata.yaml"

TAG_MAP = {
    "PII.Sensitive":    {"sensitivity": "restricted", "mask_class": "drop", "pii": True},
    "PII.NonSensitive": {"sensitivity": "default",    "mask_class": "none", "pii": True},
}
# OM table FQN prefix → the real dbt namespace (schema comes from the FQN itself)
SERVICE_PREFIX = "nhdw-vault.nhdw_vault."

_CTX = ssl.create_default_context(); _CTX.check_hostname = False; _CTX.verify_mode = ssl.CERT_NONE


def om_get(api: str, jwt: str, path: str) -> dict:
    req = urllib.request.Request(api + path, headers={"Authorization": f"Bearer {jwt}"})
    with urllib.request.urlopen(req, timeout=15, context=_CTX) as r:
        return json.loads(r.read())


def collect(api: str, jwt: str) -> list[dict]:
    """Every classified column of the vault/marts service, as target rows."""
    rows, after = [], None
    while True:
        q = f"/v1/tables?limit=100&fields=columns,tags&service=nhdw-vault" + (f"&after={after}" if after else "")
        page = om_get(api, jwt, q)
        for t in page.get("data", []):
            fqn = t.get("fullyQualifiedName", "")
            if not fqn.startswith(SERVICE_PREFIX):
                continue
            schema_table = fqn[len(SERVICE_PREFIX):]           # e.g. bi_supply.mart_ct_nodes
            if "." not in schema_table:
                continue
            schema, table = schema_table.split(".", 1)
            for col in t.get("columns", []):
                for tag in col.get("tags", []):
                    m = TAG_MAP.get(tag.get("tagFQN"))
                    if m:
                        rows.append({"schema_name": schema, "table_name": table,
                                     "column_name": col["name"], "data_class": tag.get("tagFQN"),
                                     "note": "authored in OpenMetadata", **m})
        after = page.get("paging", {}).get("after")
        if not after:
            break
    return rows


def write_seed(rows: list[dict]) -> None:
    lines = ["# GENERATED by bundle/scripts/sync-om-classification.py — the one-way",
             "# OM→ops_perm classification export (managed_by=openmetadata rows only).",
             "# Commit this file: it is the cold-boot source of the OM-authored rows.",
             "columns:"]
    for r in sorted(rows, key=lambda r: (r["schema_name"], r["table_name"], r["column_name"])):
        lines.append(f"  - {{schema: {r['schema_name']}, table: {r['table_name']}, column: {r['column_name']}, "
                     f"sensitivity: {r['sensitivity']}, mask_class: {r['mask_class']}, "
                     f"data_class: {r['data_class']}, pii: {str(r['pii']).lower()}, managed_by: openmetadata}}")
    GENERATED.write_text("\n".join(lines) + "\n")


def apply_db(dsn: str, rows: list[dict]) -> tuple[int, int]:
    import psycopg2  # available in the platform's python tooling images
    conn = psycopg2.connect(dsn); conn.autocommit = False
    cur = conn.cursor()
    cur.execute("SELECT to_regclass('ops_perm.column_classification')")
    if cur.fetchone()[0] is None:
        print("ops_perm.column_classification does not exist yet (governance "
              "workstream owns it) — nothing applied.")
        conn.close(); return (0, 0)
    n_up = 0
    for r in rows:
        cur.execute(
            """
            INSERT INTO ops_perm.column_classification
                (schema_name, table_name, column_name, sensitivity, mask_class,
                 data_class, pii, managed_by, note)
            VALUES (%(schema_name)s, %(table_name)s, %(column_name)s, %(sensitivity)s,
                    %(mask_class)s, %(data_class)s, %(pii)s, 'openmetadata', %(note)s)
            ON CONFLICT (schema_name, table_name, column_name) DO UPDATE
               SET sensitivity = EXCLUDED.sensitivity,
                   mask_class  = EXCLUDED.mask_class,
                   data_class  = EXCLUDED.data_class,
                   pii         = EXCLUDED.pii,
                   note        = EXCLUDED.note
             WHERE column_classification.managed_by = 'openmetadata'
            """, r)
        n_up += cur.rowcount
    conn.commit()
    cur.execute("SELECT count(*) FROM ops_perm.column_classification WHERE managed_by='openmetadata'")
    total = cur.fetchone()[0]
    conn.close()
    return n_up, total


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true", help="write to the DB (needs OM_CLASS_SYNC_ENABLED=true)")
    args = ap.parse_args()
    api, jwt = os.environ.get("OM_API", "").rstrip("/"), os.environ.get("OM_JWT", "")
    if not (api and jwt):
        print("OM_API / OM_JWT unset — nothing to do."); return 0
    rows = collect(api, jwt)
    print(f"classified columns found in OM: {len(rows)}")
    write_seed(rows)
    print(f"seed written: {GENERATED.relative_to(REPO)}")
    if not args.apply:
        print("dry-run (no --apply) — DB untouched."); return 0
    if os.environ.get("OM_CLASS_SYNC_ENABLED", "").lower() != "true":
        print("OM_CLASS_SYNC_ENABLED != true — feature-flagged off, DB untouched."); return 0
    dsn = os.environ.get("CLASS_DB_DSN", "")
    if not dsn:
        print("CLASS_DB_DSN unset — DB untouched."); return 0
    applied, total = apply_db(dsn, rows)
    print(f"applied (managed_by=openmetadata only): {applied} rows; total OM-managed now: {total}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
