#!/usr/bin/env python3
"""Compile bundle/roles/*.yaml → 7_security/opa/policies/*.rego.

For each role YAML, emits a Rego file under nhdw.authz.<role-id>. A top-
level common.rego is preserved (not generated) and routes incoming
requests to the right per-role decision.

The output is purely declarative — the PEP at each access point posts
(user.role, action.verb, resource.subject, resource.granularity,
context.purpose_of_use) and OPA returns
    { "allow": bool, "reason": "..." }
plus optional obligations.

Run from anywhere:
    python3 7_security/opa/scripts/compile.py
"""
from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

try:
    import yaml
except ImportError:
    print("PyYAML missing — pip install pyyaml", file=sys.stderr)
    sys.exit(1)

import json


def rego_list(items):
    """Format a Python list as a Rego array literal (double-quoted strings)."""
    return json.dumps(items)

_here = Path(__file__).resolve()
# In the repo compile.py is 7_security/opa/scripts/compile.py → parents[3] = root.
# When mounted shallow in a pod (/src/compile.py) parents[3] doesn't exist, so
# guard it — REPO is only a FALLBACK; NHDW_ROLES_DIR and --out-dir drive the real
# paths in-cluster (the equivalence-check / policy-regen Jobs).
REPO = _here.parents[3] if len(_here.parents) > 3 else _here.parent
ROLES_DIR = Path(os.environ.get("NHDW_ROLES_DIR") or (REPO / "bundle" / "roles"))
OUT_DIR = REPO / "7_security" / "opa" / "policies"


def role_id_to_module(role_id: str) -> str:
    return "role_" + role_id.lower().replace("-", "_")


def emit_role_rego(role: dict) -> str:
    """Generate Rego for one role's permission set."""
    role_id = role["id"]
    module = role_id_to_module(role_id)
    perms = role.get("permissions") or []
    lines = [
        f"# Generated by 7_security/opa/scripts/compile.py — DO NOT EDIT BY HAND.",
        f"# Source: bundle/roles/{role_id.lower()}.yaml",
        f"package nhdw.authz.role_{role_id.lower().replace('-', '_')}",
        "",
        "import rego.v1",
        "",
        f'role_id := "{role_id}"',
        f'phase   := {role["phase_activated"]}',
        f"",
        "default allow := false",
        "",
    ]
    if not perms:
        intentional = bool(role.get("intentional_deny"))
        marker = "intentional" if intentional else "stub (not yet activated)"
        lines += [
            f"# Data-plane deny-all — {marker}.",
            "# Permissions list is empty; allow stays false. The PEP reads this",
            "# as a hard deny for any mart read.",
            "",
            "decision := {",
            '  "allow":  allow,',
            f'  "reason": "{role_id} data-plane deny-all ({marker})",',
            "}",
            "",
        ]
        return "\n".join(lines)

    # Emit one `allow` rule per permission entry; OPA's default-deny means
    # ANY match grants. The PEP requests one decision at a time so the
    # union semantics here are exactly what we want.
    for i, perm in enumerate(perms):
        subject = perm["subject"]
        members = perm["members"]
        granularity = perm["granularity"]
        verbs = perm.get("verbs") or []
        purposes = perm.get("purpose_of_use") or []
        data_classes = perm.get("data_class") or []
        sensitivity = perm.get("sensitivity") or []

        # We keep matching simple — verb in list, subject equals, granularity
        # equals, purpose in list. Scope evaluation is deferred to the PEP
        # which has the full user.attributes context.
        lines += [
            f"# permission[{i}]: {subject} / members={members} / gran={granularity} / verbs={verbs}",
            f"allow if {{",
            f'  input.resource.subject == "{subject}"',
            f"  input.action.verb in {rego_list(verbs)}",
            f"  input.resource.granularity == \"{granularity}\"",
            f"  input.context.purpose_of_use in {rego_list(purposes)}",
        ]
        if data_classes:
            lines.append(f"  input.resource.data_class in {rego_list(data_classes)}")
        if members == "self":
            lines.append('  input.resource.is_self == true')
        if sensitivity:
            lines += [
                f"  # sensitivity grant — empty means default; here listed: {sensitivity}",
                f"  input.resource.sensitivity in {rego_list(sensitivity + ['default'])}",
            ]
        else:
            lines.append('  input.resource.sensitivity in ["default", ""]')
        lines.append("}")
        lines.append("")

    lines += [
        "# Top-level decision object — what the PEP gets back.",
        "decision := {",
        '  "allow":   allow,',
        f'  "reason":  sprintf("evaluated against {role_id}: allow=%v", [allow]),',
        "}",
        "",
    ]
    return "\n".join(lines)


def _role_docs_from_yaml():
    for yaml_path in sorted(ROLES_DIR.glob("*.yaml")):
        with yaml_path.open() as f:
            yield yaml.safe_load(f)["role"]


def _perms_from_db(cur, role_id: int) -> list[dict]:
    """One role's permissions from the normalized store, in YAML-declaration order
    (rp.ordering) so the emitted rego matches the YAML-sourced rego byte-for-byte."""
    cur.execute("""
        SELECT p.subject, p.members, p.granularity, p.verbs, p.purposes,
               p.data_classes, p.sensitivity
          FROM ops_perm.role_permission rp
          JOIN ops_perm.permission p ON p.id = rp.permission_id
         WHERE rp.role_id = %s
         ORDER BY rp.ordering
    """, (role_id,))
    return [
        {"subject": s, "members": m, "granularity": g, "verbs": list(v),
         "purpose_of_use": list(pu), "data_class": list(dc), "sensitivity": list(sn)}
        for s, m, g, v, pu, dc, sn in cur.fetchall()
    ]


def _roles_from_db(conn_kwargs: dict):
    """Role metadata (id, phase, intentional_deny) stays authored in the YAMLs;
    the PERMISSIONS come from ops_perm (the normalized store)."""
    import psycopg  # lazy — only needed in --from-db mode
    with psycopg.connect(**conn_kwargs) as conn, conn.cursor() as cur:
        cur.execute("SELECT code, id FROM ops_perm.role")
        code_to_id = {c: i for c, i in cur.fetchall()}
        for role in _role_docs_from_yaml():
            role = dict(role)
            rid = code_to_id.get(role["id"])
            role["permissions"] = _perms_from_db(cur, rid) if rid is not None else []
            yield role


def main() -> int:
    ap = argparse.ArgumentParser(description="Compile role permissions → OPA rego.")
    ap.add_argument("--from-db", action="store_true",
                    help="source permissions from ops_perm (DB) instead of the role YAMLs")
    ap.add_argument("--out-dir", default=str(OUT_DIR),
                    help="write rego here instead of the in-tree policies dir")
    ap.add_argument("--pg-host", default=os.environ.get("POSTGRES_HOST", "localhost"))
    ap.add_argument("--pg-port", default=os.environ.get("POSTGRES_PORT", "5432"))
    ap.add_argument("--pg-user", default=os.environ.get("POSTGRES_USER", "postgres"))
    ap.add_argument("--pg-db",   default=os.environ.get("OPS_DB_NAME", "nhdw_ops"))
    args = ap.parse_args()

    if not ROLES_DIR.is_dir():
        print(f"roles dir not found: {ROLES_DIR}", file=sys.stderr)
        return 1
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    if args.from_db:
        conn_kwargs = dict(host=args.pg_host, port=args.pg_port, user=args.pg_user,
                           dbname=args.pg_db, password=os.environ.get("PGPASSWORD"))
        roles, src = _roles_from_db(conn_kwargs), "DB (ops_perm)"
    else:
        roles, src = _role_docs_from_yaml(), "bundle/roles/*.yaml"

    written = []
    for role in roles:
        out_path = out_dir / f"{role_id_to_module(role['id'])}.rego"
        out_path.write_text(emit_role_rego(role))
        written.append((role["id"], out_path.name, len(role.get("permissions") or [])))

    print(f"compiled from {src}:")
    for rid, fname, n in written:
        print(f"  {rid:14}  →  {fname}  ({n} permission entries)")
    print(f"total: {len(written)} role policies → {out_dir}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
