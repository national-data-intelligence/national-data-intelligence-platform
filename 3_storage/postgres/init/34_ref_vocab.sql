-- nhdw_ref — the governed reference-data vocabulary & terminology schema (OMOP-style).
--
-- Single source of truth for "what does this code mean": canonical concepts plus the
-- crosswalks from every source system's native codes to them. Replaces the
-- code-embedded mappings (build_sample.py dicts, resolution-view CASEs) with governed,
-- versioned, steward-editable DATA. Designed so adding a standard vocabulary
-- (ICD-10, ATC, LOINC, …) is rows + a loader, never a code change.
--
-- Ownership / flow:
--   * DDL here (runs at database init, so the schema exists before any dbt build).
--   * Data is loaded by bundle/scripts/seed-ref-vocab.sh from the CSVs generated by
--     bundle/seeds/ref-vocab/build_vocab.py (idempotent upsert; re-runnable any time).
--   * The vault resolution views (2_pipelines/vault/models/business_vault/
--     conformed_hubs/v_*_resolution.sql) JOIN source_to_concept_map — migrated
--     vocabulary-by-vocabulary, PARITY-FIRST: a mapping ships only after proving
--     byte-identical conformed keys against the previous logic.
--   * Bitemporal contract: valid_from/valid_to (+ invalid_reason) on every mapping
--     row; supersede by closing valid_to and inserting a new row — never UPDATE a
--     mapping in place.
--
-- PARITY RULE (load-bearing, do not violate): for any domain consumed by a
-- resolution view, concept.concept_code MUST equal the conformed_bk string the view
-- produced before migration (programme ids like 'HIV'; commodity norm_names; …) —
-- the conformed hash keys are SHA-256 over that string, so an equal code is what
-- keeps hk_*_conformed byte-identical.
--
-- Idempotent.

CREATE SCHEMA IF NOT EXISTS nhdw_ref;
COMMENT ON SCHEMA nhdw_ref IS
  'Governed reference vocabulary + terminology (OMOP-style): concepts and source-code crosswalks.';

-- ── metamodel ────────────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS nhdw_ref.vocabulary (
    vocabulary_id        text PRIMARY KEY,          -- e.g. NHDW-PROGRAMME, DHIS2.dataElement, ICD10
    vocabulary_name      text NOT NULL,
    vocabulary_reference text,                      -- where the standard lives (URL / doc)
    vocabulary_version   text,                      -- version/release of the loaded subset
    is_source_vocabulary boolean NOT NULL DEFAULT false  -- true = a source system's code space
);
COMMENT ON TABLE nhdw_ref.vocabulary IS
  'Every code space known to the warehouse — internal canonical sets and source/standard vocabularies.';

CREATE TABLE IF NOT EXISTS nhdw_ref.domain (
    domain_id   text PRIMARY KEY,                   -- programme | indicator | commodity | geography | …
    domain_name text NOT NULL
);

CREATE TABLE IF NOT EXISTS nhdw_ref.concept_class (
    concept_class_id   text PRIMARY KEY,
    concept_class_name text NOT NULL
);

CREATE TABLE IF NOT EXISTS nhdw_ref.concept (
    concept_id       bigint PRIMARY KEY,            -- stable id from the committed registry
                                                    -- (bundle/seeds/ref-vocab/concept_registry.json);
                                                    -- local concepts live in the >= 2 000 000 000
                                                    -- range per OMOP convention
    concept_name     text NOT NULL,
    domain_id        text NOT NULL REFERENCES nhdw_ref.domain(domain_id),
    vocabulary_id    text NOT NULL REFERENCES nhdw_ref.vocabulary(vocabulary_id),
    concept_class_id text NOT NULL REFERENCES nhdw_ref.concept_class(concept_class_id),
    standard_concept text,                          -- 'S' = the canonical concept for its domain
    concept_code     text NOT NULL,                 -- see the PARITY RULE above
    valid_from       date NOT NULL DEFAULT current_date,
    valid_to         date NOT NULL DEFAULT '2099-12-31',
    invalid_reason   text                           -- NULL = live; 'D' deprecated; 'U' upgraded
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_concept_vocab_code
    ON nhdw_ref.concept (vocabulary_id, concept_code, valid_from);
CREATE INDEX IF NOT EXISTS ix_concept_code ON nhdw_ref.concept (concept_code);
COMMENT ON TABLE nhdw_ref.concept IS
  'Canonical entities (programmes, commodities, regions, tiers, diseases, indicators, …) and standard-vocabulary codes.';

CREATE TABLE IF NOT EXISTS nhdw_ref.concept_relationship (
    concept_id_1    bigint NOT NULL REFERENCES nhdw_ref.concept(concept_id),
    concept_id_2    bigint NOT NULL REFERENCES nhdw_ref.concept(concept_id),
    relationship_id text   NOT NULL,                -- 'Maps to' | 'Has programme' | 'Outbreak response' | …
    valid_from      date   NOT NULL DEFAULT current_date,
    valid_to        date   NOT NULL DEFAULT '2099-12-31',
    invalid_reason  text,
    PRIMARY KEY (concept_id_1, concept_id_2, relationship_id, valid_from)
);
COMMENT ON TABLE nhdw_ref.concept_relationship IS
  'Typed edges between concepts (hierarchies, standard-code bridges like ATC↔commodity). NOT on the conformed-key parity path.';

-- ── the crosswalk (what the resolution views JOIN) ───────────────────────────

CREATE TABLE IF NOT EXISTS nhdw_ref.source_to_concept_map (
    source_code             text   NOT NULL,        -- the code as the source system emits it
    source_vocabulary_id    text   NOT NULL REFERENCES nhdw_ref.vocabulary(vocabulary_id),
    source_code_description text,
    target_concept_id       bigint NOT NULL REFERENCES nhdw_ref.concept(concept_id),
    valid_from              date   NOT NULL DEFAULT current_date,
    valid_to                date   NOT NULL DEFAULT '2099-12-31',
    invalid_reason          text,
    change_source           text   NOT NULL DEFAULT 'seed'
                            CHECK (change_source IN ('seed','steward','openmetadata')),
    loaded_by               text,
    loaded_at               timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (source_code, source_vocabulary_id, valid_from)
);
CREATE INDEX IF NOT EXISTS ix_s2c_target ON nhdw_ref.source_to_concept_map (target_concept_id);
COMMENT ON TABLE nhdw_ref.source_to_concept_map IS
  'Source-code → canonical-concept crosswalk. The governed replacement for regex/dict mappings; resolution views JOIN this.';

-- ── access ───────────────────────────────────────────────────────────────────
-- vault_writer: the dbt vault build JOINs the crosswalk at model-build time.
-- bi_reader:    dashboards/marts and the gateway read concepts for display/glossary.
-- Writes stay with the admin/loader path (seed-ref-vocab.sh) and, later, the
-- steward console route — which will receive its own scoped role when it lands.
GRANT USAGE ON SCHEMA nhdw_ref TO vault_writer, bi_reader;
GRANT SELECT ON ALL TABLES IN SCHEMA nhdw_ref TO vault_writer, bi_reader;
ALTER DEFAULT PRIVILEGES IN SCHEMA nhdw_ref
    GRANT SELECT ON TABLES TO vault_writer, bi_reader;
